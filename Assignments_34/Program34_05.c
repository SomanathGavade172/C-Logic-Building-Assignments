/* 
    5. Write a program which accept one number from user and toggle contents of first and last nibble of the number. Return modified number. (Nibble is a group of four bits).
    
*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : ToggleBit
//  Description    : This function toggles the contents of first and last nibble of the number.
//  Input          : Integer
//  Output         : Returns modified number after toggling first and last nibble
//  Author         : Gavade Somanath Vilas
//  Date           : 22/04/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int ToggleBit(int iNo)
{
    int iMask = 0xF000000F;
    int iResult = 0;

    iResult = iNo ^ iMask;

    return iResult;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Toggle Nibble Program
//  Description      : This application accepts a number from user and toggles contents of first and last nibble.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{   
    int iValue = 0;
    int iRet = 0;

    printf("Enter a Number : \n");
    scanf("%d", &iValue);

    iRet = ToggleBit(iValue);

    printf("Number after nibble Toggle : %d\n", iRet);

    return 0;
}