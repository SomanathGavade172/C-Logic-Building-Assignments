#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : DisplayDigit
//  Description    : This function displays only digit characters from the given string.
//  Input          : String (character array)
//  Output         : None (Displays digits directly)
//  Author         : Gavade Somanath Vilas
//  Date           : 26/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

// Function definition
void DisplayDigit(char *str)
{
    while(*str != '\0')
    {
        if(*str >= '0' && *str <= '9')
        {
            printf("%c", *str);
        }        
        str++;
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Display Digits From String
//  Description      : This application accepts a string from user and displays only the digits present in it.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char Arr[30];

    printf("Enter a String : \n");
    scanf("%[^\n]", Arr);

    DisplayDigit(Arr);           // Function Call

    return 0;
}