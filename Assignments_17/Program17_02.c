/* 
    2.Write a program which accept number from user and print numbers till that number.

    Input  : 8

    Output : 1 2 3 4 5 6 7 8

*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : Display
//  Description    : Displays numbers from 1 to the given number on the screen.
//  Input          : Integer
//  Output         : None (Prints numbers on the screen)
//  Author         : Gavade Somanath Vilas
//  Date           : 26/01/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    int iCnt = 0;
    if(iNo < 0)
    {
        iNo = -iNo;
    }

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("%d\t", iCnt);
    }
}


///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name    :   Number Printing
//  Description         :   This application accepts a number from the user and prints numbers from 1 to that number
//                          on the screen.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter a number : ");
    scanf("%d", &iValue);

    Display(iValue);
    
    return 0;
}
