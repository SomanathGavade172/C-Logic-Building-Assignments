/* 
    3. Write a program which accept number from user and print its numbers line.

    Input  : 4

    Output : -4 -3 -2 -1 0 1 2 3 4

*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : Display
//  Description    : Displays the number line from negative of the given number to positive of the given number.
//  Input          : Integer
//  Output         : None (Prints numbers on the screen)
//  Author         : Gavade Somanath Vilas
//  Date           : 26/01/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


void Display(int iNo)
{
    int iCnt = 0;
   
    for(iCnt = -iNo; iCnt <= iNo; iCnt++)
    {
        printf("%d\t", iCnt);
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name    :   Number Line Printing
//  Description         :   This application accepts a number from the user and prints its number line from -N to +N
//                          on the screen.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter a number : ");
    scanf("%d", &iValue);

    Display(iValue);
    
    return 0;
}
