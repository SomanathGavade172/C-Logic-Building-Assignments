/* 
    5. Write a program which accepts N from user and print first 5 multiples of N.

    Input  : 4
    Output : 4  8  12  16  20
*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : MultiDisplay
//  Description    : Prints the first five multiples of the given number.
//  Input          : Integer (N)
//  Output         : None (Displays multiples on the screen)
//  Author         : Gavade Somanath Vilas
//  Date           : 30/01/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

// Function Definition
void MultiDisplay(int iNo)
{
    int iCnt = 0;
    int iMulti = 1;
    
    for(iCnt = 1; iCnt <= 5; iCnt++)
    {   
        iMulti = iNo * iCnt;
        printf("%d\t", iMulti);
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Multiples Display
//  Description      : This application accepts a number from the user and prints its first five multiples.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter a number : ");
    scanf("%d", &iValue);

    MultiDisplay(iValue);           //  Function Call.

    return 0;
}
