/* 
    4. Write a program which accepts N from user and print all odd numbers up to N.

    Input  : 18

    Output : 1 3 5 7 9 11 13 17

*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : OddDisplay
//  Description    : Displays all odd numbers from 1 up to the given number.
//  Input          : Integer
//  Output         : None (Prints odd numbers on the screen)
//  Author         : Gavade Somanath Vilas
//  Date           : 27/01/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

// Function Definition
void OddDisplay(int iNo)
{
    int iCnt = 0;
    
    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {   
        if(iCnt % 2 != 0)
        {
            printf("%d\t", iCnt);
        }        
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Odd Number Display
//  Description      : This application accepts a number from the user and prints all odd numbers up to that number on the screen.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter a number : ");
    scanf("%d", &iValue);

    OddDisplay(iValue);    

    return 0;
}