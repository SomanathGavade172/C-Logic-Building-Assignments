/* 
    1. Accept number from user and display below pattern.

    Input  : 5

    Output : A B C D E
*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : Pattern
//  Description    : Displays alphabet pattern starting from 'A' up to the given count.
//  Input          : Integer
//  Output         : NONE (Displays characters on console)
//  Author         : Gavade Somanath Vilas
//  Date           : 01/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

// Function Definition
void Pattern(int iNo)
{
    int iCnt = 0;

    for(iCnt = 0; iCnt < iNo; iCnt++)
    {
        printf("%c\t", 65 + iCnt);
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Alphabet Pattern Display
//  Description      : This application accepts a number from the user and displays alphabets starting from 'A' up to the given number.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{   
    int iValue = 0;

    printf("Enter number of elements : \n");
    scanf("%d", &iValue);

    Pattern(iValue);            //  Function Call.

    return 0;
}
