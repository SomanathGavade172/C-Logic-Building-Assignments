/* 
    3. Accept a number from the user and display the below pattern.

    Input  : 5
    Output : 1 * 2 * 3 * 4 * 5 *

*/

#include<stdio.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : Pattern
//  Description    : Displays numbers from 1 to given number followed by '*' symbol.
//  Input          : Integer
//  Output         : NONE (Displays pattern on console)
//  Author         : Gavade Somanath Vilas
//  Date           : 02/02/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

// Function Definition
void Pattern(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("%d\t*\t ", iCnt);
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Number Pattern Display
//  Description      : This application accepts a number from the user and displays numbers from 1 to that number followed by '*' symbol.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{   
    int iValue = 0;

    printf("Enter number : \n");
    scanf("%d", &iValue);

    Pattern(iValue);            // Function Call

    return 0;
}
