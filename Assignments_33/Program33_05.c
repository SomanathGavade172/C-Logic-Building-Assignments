/* 
    5. Write a program which accept one number from user and on its first 4 bits. Return modified number.

    Input  : 73
    Output : 79
    
*/

#include<stdio.h>

typedef unsigned int UINT;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : OnBit
//  Description    : This function turns ON the first 4 bits of the given number.
//  Input          : Integer
//  Output         : Returns modified number after turning ON first 4 bits
//  Author         : Gavade Somanath Vilas
//  Date           : 19/04/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int OnBit(UINT iNo)
{
    int iMask = 0xF;
    int iResult = 0;

    iResult = iNo | iMask;

    return iResult;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : On First 4 Bits Program
//  Description      : This application accepts a number from the user and turns ON its first 4 bits.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter a Number : \n");
    scanf("%d", &iValue);

    iRet = OnBit(iValue);

    printf("Number after turning ON first 4 bits is : %d\n", iRet);

    return 0;
}