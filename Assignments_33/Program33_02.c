/*
    2. Write a program which accept one number from user and off 7th and 10th bit of that number. Return modified number.

        Input  : 577
        Output : 1
        
*/

#include<stdio.h>

typedef unsigned int UINT;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : OffBit
//  Description    : This function turns OFF the 7th and 10th bits of the given number if they are ON.
//  Input          : Integer
//  Output         : Returns modified number after turning OFF 7th and 10th bits
//  Author         : Gavade Somanath Vilas
//  Date           : 19/04/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int OffBit(UINT iNo)
{
    int iMask = 0xFFFFFDBF;
    int iResult = 0;

    iResult = iNo & iMask;

    return iResult;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Off 7th and 10th Bit Program
//  Description      : This application accepts a number from the user and turns OFF its 7th and 10th bits.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter a Number : \n");
    scanf("%d", &iValue);

    iRet = OffBit(iValue);

    printf("Number after 7th and 10th bits off is : %d\n", iRet);

    return 0;
}