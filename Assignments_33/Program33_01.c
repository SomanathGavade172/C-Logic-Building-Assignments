/* 
    1. Write a program which accept one number from user and off 7th bit of that number if it is on. Return modified number.

        Input  : 79
        Output : 15

*/

#include<stdio.h>

typedef unsigned int UINT;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name  : OffBit
//  Description    : This function turns OFF the 7th bit of the given number if it is ON.
//  Input          : Integer
//  Output         : Returns modified number after turning OFF 7th bit
//  Author         : Gavade Somanath Vilas
//  Date           : 19/04/2026
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int OffBit(UINT iNo)
{
    int iMask = 0xFFFFFFBF;
    int iResult = 0;

    iResult = iNo & iMask;

    return iResult;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Application Name : Off 7th Bit Program
//  Description      : This application accepts a number from the user and turns OFF its 7th bit.
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter a Number : \n");
    scanf("%d", &iValue);

    iRet = OffBit(iValue);

    printf("Number after 7th bit off is : %d\n", iRet);

    return 0;
}